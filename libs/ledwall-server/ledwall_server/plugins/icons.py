_ICON_SETS: dict[IconSize, dict[str, list[str]]] = {
    IconSize.S: ICONS_S,
    IconSize.L: ICONS_L,
}


def get_icon(name: str, size: IconSize = IconSize.L) -> list[str] | None:
    """Look up a bitmap icon by name and size."""
    return _ICON_SETS[size].get(name)
